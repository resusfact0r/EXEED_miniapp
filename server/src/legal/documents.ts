import type { Seller } from './seller';

export const DOCUMENTS = ['privacy', 'consent', 'terms'] as const;
export type DocumentName = (typeof DOCUMENTS)[number];

const escapeHtml = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function page(title: string, body: string): string {
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>${title}</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:720px;margin:0 auto;padding:16px;color:#1a1a1a;background:#fff}
h1{font-size:22px}h2{font-size:17px;margin-top:24px}
@media(prefers-color-scheme:dark){body{color:#eee;background:#17212b}}</style></head>
<body><h1>${title}</h1>${body}</body></html>`;
}

function privacy(_s: Seller, seller: string, email: string): string {
  return page(
    'Политика обработки персональных данных',
    `<p>Оператор персональных данных: ${seller}. Контакт для обращений: ${email}.</p>
<h2>Какие данные мы обрабатываем</h2>
<p>Идентификатор, имя и имя пользователя в Telegram; номер телефона; выбранный пункт выдачи и его адрес; сведения о заказах; реквизиты организации, если покупатель их указал.</p>
<h2>Зачем</h2>
<p>Чтобы оформить и выполнить заказ, принять оплату, передать заказ в доставку, связаться с покупателем по заказу и выполнить обязанности, установленные законом.</p>
<h2>Основания</h2>
<p>Согласие покупателя и договор, стороной которого он является.</p>
<h2>Кому мы передаём данные</h2>
<p>Службам доставки СДЭК и Яндекс Доставка — для доставки заказа; платёжному сервису — для приёма оплаты. Приложение работает внутри Telegram: сообщения покупателю и операторам магазина передаются через этот сервис, его серверы могут находиться за пределами России.</p>
<h2>Где и сколько хранятся данные</h2>
<p>База данных находится на сервере в России. Данные хранятся, пока это нужно для перечисленных целей и выполнения требований закона, затем удаляются.</p>
<h2>Ваши права</h2>
<p>Вы можете узнать, какие данные мы обрабатываем, потребовать их уточнить или удалить и отозвать согласие. Для этого напишите на ${email}. Если согласие отозвано, выполнить новые заказы мы не сможем.</p>`,
  );
}

function consent(_s: Seller, seller: string, email: string): string {
  return page(
    'Согласие на обработку персональных данных',
    `<p>Я свободно, своей волей и в своём интересе даю согласие оператору — ${seller} — на обработку моих персональных данных.</p>
<p><b>Данные:</b> идентификатор, имя и имя пользователя в Telegram, номер телефона, адрес пункта выдачи, сведения о заказах.</p>
<p><b>Цели:</b> оформление и выполнение заказов, приём оплаты, доставка, связь со мной по заказам.</p>
<p><b>Действия:</b> сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, передача службам доставки и платёжному сервису, блокирование, удаление, уничтожение, с использованием средств автоматизации и без них.</p>
<p><b>Срок:</b> согласие действует, пока это нужно для указанных целей, или до его отзыва.</p>
<p>Я могу отозвать согласие, написав на ${email}.</p>`,
  );
}

function terms(s: Seller, seller: string, email: string): string {
  const phone = s.phone ? `, ${escapeHtml(s.phone)}` : '';
  return page(
    'Условия покупки и возврата',
    `<p>Продавец: ${seller}. Контакты: ${email}${phone}.</p>
<h2>Цена и заказ</h2>
<p>Цена и наличие проверяются у поставщика при оформлении заказа. Если они изменились, покупатель увидит новые условия и подтвердит их заново.</p>
<h2>Оплата</h2>
<p>После оформления заказа мы присылаем ссылку на оплату в чат с ботом. Юридические лица оплачивают по счёту.</p>
<h2>Получение</h2>
<p>Самовывоз или доставка в пункт выдачи СДЭК и Яндекс Доставки. Примерная стоимость доставки показывается при выборе пункта, точная — в ссылке на оплату.</p>
<h2>Возврат</h2>
<p>Покупатель вправе отказаться от товара до его получения, а после получения — в течение 7 дней. Товар надлежащего качества принимается, если сохранены его товарный вид и потребительские свойства, а также документ, подтверждающий покупку. Деньги возвращаются не позднее 10 дней с даты требования, за вычетом расходов продавца на доставку товара покупателю.</p>
<p>Товар ненадлежащего качества возвращается и обменивается в порядке, установленном законом.</p>
<p>Чтобы оформить возврат, напишите на ${email}.</p>`,
  );
}

export function renderDocument(name: DocumentName, s: Seller): string {
  const seller = escapeHtml(`${s.name}, ОГРН ${s.ogrn}, ИНН ${s.inn}, адрес: ${s.address}`);
  const email = escapeHtml(s.email);
  return { privacy, consent, terms }[name](s, seller, email);
}
