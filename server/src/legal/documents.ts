export function renderDocument(name: DocumentName, s: Seller, botUsername: string | null): string {
  const operator = escapeHtml(`${s.name} (${isSoleTrader(s) ? 'ОГРНИП' : 'ОГРН'} ${s.ogrn}, ИНН ${s.inn}, адрес: ${s.address})`);
  const contact = escapeHtml(contactLine(s, botUsername));
  return { privacy, consent, terms }[name]({ operator, contact, s });
}
